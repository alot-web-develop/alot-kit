import { SEMANTIC_COLORS } from "./colors.js";
import type { TColorScheme, TTheme } from "./types.js";

type TDarkStrategy = "class" | "media";

const indent = (lines: string[], depth: number) =>
  lines.map((line) => `${"  ".repeat(depth)}${line}`);

const colorVars = (theme: TTheme, scheme: TColorScheme) =>
  SEMANTIC_COLORS.map((name) => `--${name}: ${theme.colors[scheme][name]};`);

const REM_IN_PX = 16;

const radiusFor = (radius: string, strategy: TDarkStrategy) => {
  const rem = /^(\d*\.?\d+)rem$/.exec(radius.trim());
  return strategy === "media" && rem
    ? `${Number(rem[1]) * REM_IN_PX}px`
    : radius;
};

const baseVars = (theme: TTheme, strategy: TDarkStrategy) => [
  `--radius: ${radiusFor(theme.radius, strategy)};`,
  `--typeface-sans: ${theme.typefaces.sans};`,
  `--typeface-heading: ${theme.typefaces.heading};`,
  `--typeface-mono: ${theme.typefaces.mono};`,
];

const isDarkOnly = (theme: TTheme) =>
  theme.schemes.length === 1 && theme.schemes[0] === "dark";

const block = (selector: string, lines: string[], depth = 0) => [
  ...indent([`${selector} {`], depth),
  ...indent(lines, depth + 1),
  ...indent(["}"], depth),
];

const renderVariables = (theme: TTheme, strategy: TDarkStrategy) => {
  if (isDarkOnly(theme)) {
    const colorScheme = strategy === "class" ? ["color-scheme: dark;"] : [];
    return block(":root", [
      ...colorScheme,
      ...baseVars(theme, strategy),
      ...colorVars(theme, "dark"),
    ]);
  }
  const root = block(":root", [
    ...baseVars(theme, strategy),
    ...colorVars(theme, "light"),
  ]);
  const dark =
    strategy === "class"
      ? block(".dark", ["color-scheme: dark;", ...colorVars(theme, "dark")])
      : [
          "@media (prefers-color-scheme: dark) {",
          ...block(":root", colorVars(theme, "dark"), 1),
          "}",
        ];
  return [...root, "", ...dark];
};

const themeMapping = () =>
  block("@theme inline", [
    ...SEMANTIC_COLORS.map((name) => `--color-${name}: var(--${name});`),
    "--radius-sm: calc(var(--radius) - 4px);",
    "--radius-md: calc(var(--radius) - 2px);",
    "--radius-lg: var(--radius);",
    "--radius-xl: calc(var(--radius) + 4px);",
    "--radius-2xl: calc(var(--radius) + 8px);",
    "--font-sans: var(--typeface-sans);",
    "--font-heading: var(--typeface-heading);",
    "--font-mono: var(--typeface-mono);",
  ]);

const HEADER = "/* Generated by @alot-web-develop/design. Do not edit. */";

const renderTokensCss = (theme: TTheme) =>
  [HEADER, ...renderVariables(theme, "class"), ""].join("\n");

const renderTailwindCss = (theme: TTheme) =>
  [
    HEADER,
    "@custom-variant dark (&:where(.dark, .dark *));",
    "",
    ...themeMapping(),
    "",
    ...renderVariables(theme, "class"),
    "",
  ].join("\n");

const renderNativewindCss = (theme: TTheme) =>
  [HEADER, ...themeMapping(), "", ...renderVariables(theme, "media"), ""].join(
    "\n",
  );

const renderThemeOverrideCss = (theme: TTheme, strategy: TDarkStrategy) =>
  [HEADER, ...renderVariables(theme, strategy), ""].join("\n");

export type { TDarkStrategy };
export {
  renderNativewindCss,
  renderTailwindCss,
  renderThemeOverrideCss,
  renderTokensCss,
};
