import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";
import { resolveInside } from "./safePath.js";

const HEADER = "// Generated by alot-gen api-contracts. Do not edit.\n";

const contractTokens = (source: string): string | undefined => {
  const diagnostics = ts.transpileModule(source, {
    reportDiagnostics: true,
  }).diagnostics;
  if (
    diagnostics?.some((item) => item.category === ts.DiagnosticCategory.Error)
  )
    return undefined;
  const file = ts.createSourceFile(
    "contracts.ts",
    source,
    ts.ScriptTarget.Latest,
    true,
  );
  const normalized = ts.createPrinter({ removeComments: true }).printFile(file);
  const scanner = ts.createScanner(
    ts.ScriptTarget.Latest,
    true,
    ts.LanguageVariant.Standard,
    normalized,
  );
  const tokens: [number, string][] = [];
  for (
    let token = scanner.scan();
    token !== ts.SyntaxKind.EndOfFileToken;
    token = scanner.scan()
  ) {
    tokens.push([
      token,
      token === ts.SyntaxKind.StringLiteral
        ? scanner.getTokenValue()
        : scanner.getTokenText(),
    ]);
  }
  return JSON.stringify(tokens);
};

interface TContractsOptions {
  cwd: string;
  input: string;
  output?: string;
  check?: boolean;
  force?: boolean;
}

const generateApiContracts = async (
  options: TContractsOptions,
): Promise<string> => {
  const destination = resolveInside(
    options.cwd,
    options.output ?? "src/types/main-api-types.ts",
  );
  const previous = existsSync(destination)
    ? readFileSync(destination, "utf8")
    : undefined;
  if (
    previous !== undefined &&
    !previous.startsWith(HEADER) &&
    !options.force &&
    !options.check
  ) {
    throw new Error(
      "contracts destination is not generated by alot-gen; choose another output or explicitly use --force",
    );
  }
  const input = /^https?:\/\//.test(options.input)
    ? new URL(options.input)
    : pathToFileURL(resolve(options.cwd, options.input));
  const ast = await openapiTS(input, { alphabetize: true });
  const contents = `${HEADER}${astToString(ast)}`;
  const schemas = ast
    .flatMap((node) => {
      if (!ts.isInterfaceDeclaration(node) || node.name.text !== "components")
        return [];
      return node.members.flatMap((member) => {
        if (
          !ts.isPropertySignature(member) ||
          !ts.isIdentifier(member.name) ||
          member.name.text !== "schemas" ||
          !member.type ||
          !ts.isTypeLiteralNode(member.type)
        )
          return [];
        return member.type.members.flatMap((schema) =>
          ts.isPropertySignature(schema) &&
          (ts.isIdentifier(schema.name) || ts.isStringLiteral(schema.name))
            ? [schema.name.text]
            : [],
        );
      });
    })
    .sort();
  const aliases = schemas
    .filter((name) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(name))
    .map(
      (name) =>
        `type T${name} = components["schemas"][${JSON.stringify(name)}];`,
    );
  const exports = schemas
    .filter((name) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(name))
    .map((name) => `T${name}`);
  const result = aliases.length
    ? `${contents}\n${aliases.join("\n")}\n\nexport type { ${exports.join(", ")} };\n`
    : contents;
  if (options.check) {
    const actual =
      previous === undefined ? undefined : contractTokens(previous);
    if (actual === undefined || actual !== contractTokens(result))
      throw new Error(
        "generated API contracts are missing or stale; regenerate them",
      );
    return destination;
  }
  mkdirSync(dirname(destination), { recursive: true });
  writeFileSync(destination, result);
  return destination;
};

const runContractsCli = async (args: string[]): Promise<number> => {
  try {
    const { values } = parseArgs({
      args,
      options: {
        input: { type: "string" },
        output: { type: "string" },
        check: { type: "boolean" },
        force: { type: "boolean" },
      },
    });
    if (!values.input)
      throw new Error(
        "usage: alot-gen api-contracts --input <OpenAPI file or URL> [--output <path>] [--check] [--force]",
      );
    const destination = await generateApiContracts({
      cwd: process.cwd(),
      input: values.input,
      output: values.output,
      check: values.check,
      force: values.force,
    });
    console.log(`${values.check ? "verified" : "generated"} ${destination}`);
    return 0;
  } catch (error) {
    console.error(
      `alot-gen: ${error instanceof Error ? error.message : String(error)}`,
    );
    return 1;
  }
};

export { generateApiContracts, runContractsCli };
